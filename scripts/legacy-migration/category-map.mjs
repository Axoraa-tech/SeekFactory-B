export function mapCategory(category, subcategory) {
  const exact = CATEGORY_MAP[`${category} > ${subcategory}`];
  if (exact) return exact;
  const c = (category || "").toLowerCase() + " ";
  const hit = Object.keys(ROOT_FALLBACK).find((k) => c.startsWith(k));
  return hit ? ROOT_FALLBACK[hit] : "cat-other";
}
